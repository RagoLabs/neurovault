import { Link, useNavigate, useParams } from 'react-router'
import { Brain, FileDown, Pencil, Stethoscope, ArrowRight } from 'lucide-react'
import { PageTransition } from '@/components/shared/PageTransition'
import { PageHeader } from '@/components/shared/PageHeader'
import { SectionCard } from '@/components/shared/SectionCard'
import { KeyValue } from '@/components/shared/KeyValue'
import { StatusBadge } from '@/components/shared/StatusBadge'
import { PatientChip } from '@/components/shared/PatientChip'
import { Button } from '@/components/ui/button'
import { NotFound } from '@/pages/NotFound'
import { useDataset } from '@/services/repository'
import { fmtDate, fullName } from '@/utils/format'
import { savePdf } from '@/utils/export'
import { surgeon } from '@/config/surgeon'
import { toast } from 'sonner'

export function ConsultationDetailPage() {
  const { id } = useParams()
  const d = useDataset()
  const navigate = useNavigate()
  const c = d.consultations.find((x) => x.id === id)
  if (!c) return <NotFound />
  const patient = d.patients.find((p) => p.id === c.patientId)
  const linkedCase = c.caseId ? d.cases.find((x) => x.id === c.caseId) : undefined
  const hospital = d.hospitals.find((h) => h.id === c.hospitalId)

  const exportPdf = () => {
    savePdf({
      title: 'Consultation note',
      subtitle: `${fullName(patient)} · ${patient?.patientNumber} · ${fmtDate(c.date)}`,
      meta: [surgeon.fullName, hospital?.name ?? ''],
      sections: [
        { heading: 'Presentation', keyValues: [['Chief complaint', c.chiefComplaint], ['History', c.historyOfPresentingIllness], ['Relevant history', c.relevantMedicalHistory]] },
        { heading: 'Examination and diagnosis', keyValues: [['Examination', c.examinationFindings], ['Working diagnosis', c.workingDiagnosis], ['Differential', c.differentialDiagnosis]] },
        { heading: 'Investigations', keyValues: [['Requested', c.investigationsRequested], ['Findings', c.investigationFindings]] },
        { heading: 'Plan', keyValues: [['Management', c.managementPlan], ['Follow-up', c.followUpRecommendations]] },
      ],
      footer: `${surgeon.signatureLine} · Generated by NeuroVault (fictional demonstration data)`,
      watermark: 'DEMO',
    }, `consultation-${patient?.patientNumber}-${c.date}.pdf`)
    toast.success('Consultation PDF generated')
  }

  return (
    <PageTransition>
      <PageHeader
        title="Consultation"
        eyebrow={fmtDate(c.date)}
        description={<span className="inline-flex items-center gap-2"><StatusBadge kind="consultation" value={c.status} /> {hospital?.name}</span>}
        actions={
          <>
            <Button variant="outline" onClick={exportPdf}><FileDown /> Export PDF</Button>
            <Button asChild variant="outline"><Link to={`/consultations/${c.id}/edit`}><Pencil /> Edit</Link></Button>
            {linkedCase ? (
              <Button asChild><Link to={`/cases/${linkedCase.id}`}><Brain /> Open case {linkedCase.caseNumber} <ArrowRight /></Link></Button>
            ) : (
              <Button onClick={() => navigate(`/cases/new?patient=${c.patientId}&consultation=${c.id}`)} disabled={c.status !== 'completed'} title={c.status !== 'completed' ? 'Complete the consultation first' : undefined}><Brain /> Initiate surgical case</Button>
            )}
          </>
        }
      />
      <div className="grid gap-4 lg:grid-cols-3">
        <div className="space-y-4 lg:col-span-2">
          <SectionCard title="Presentation" icon={Stethoscope}>
            <KeyValue columns={1} items={[{ label: 'Chief complaint', value: c.chiefComplaint }, { label: 'History of presenting illness', value: c.historyOfPresentingIllness }, { label: 'Relevant medical history', value: c.relevantMedicalHistory }]} />
          </SectionCard>
          <SectionCard title="Examination and diagnosis">
            <KeyValue columns={1} items={[{ label: 'Examination findings', value: c.examinationFindings }, { label: 'Working diagnosis', value: <span className="font-semibold">{c.workingDiagnosis}</span> }, { label: 'Differential diagnosis', value: c.differentialDiagnosis }]} />
          </SectionCard>
          <SectionCard title="Investigations">
            <KeyValue columns={2} items={[{ label: 'Requested', value: c.investigationsRequested }, { label: 'Findings', value: c.investigationFindings }]} />
          </SectionCard>
          <SectionCard title="Plan">
            <KeyValue columns={1} items={[{ label: 'Management plan', value: c.managementPlan }, { label: 'Follow-up recommendations', value: c.followUpRecommendations }]} />
          </SectionCard>
        </div>
        <div className="space-y-4">
          <SectionCard title="Patient">
            <PatientChip patientId={c.patientId} />
            {patient && <div className="mt-3 text-sm text-muted-foreground">{patient.primaryDiagnosis}</div>}
            <Button asChild variant="outline" size="sm" className="mt-3"><Link to={`/patients/${c.patientId}`}>Open profile</Link></Button>
          </SectionCard>
          <SectionCard title="Linked surgical case" icon={Brain}>
            {linkedCase ? (
              <div className="space-y-2 text-sm">
                <Link to={`/cases/${linkedCase.id}`} className="font-semibold hover:underline">{linkedCase.caseNumber}</Link>
                <div>{linkedCase.plannedProcedure}</div>
                <div className="flex gap-2"><StatusBadge kind="caseType" value={linkedCase.type} /><StatusBadge kind="case" value={linkedCase.status} /></div>
              </div>
            ) : <p className="text-sm text-muted-foreground">No surgical case has been initiated from this consultation.</p>}
          </SectionCard>
          <SectionCard title="Documentation">
            <KeyValue columns={1} items={[{ label: 'Clinician', value: surgeon.fullName }, { label: 'Template', value: d.noteTemplates.find((t) => t.id === c.templateId)?.name }, { label: 'Record ID', value: <span className="font-data">{c.id}</span> }]} />
          </SectionCard>
        </div>
      </div>
    </PageTransition>
  )
}
